/// Name for a key code, or `RC_UNKNOWN` outside the table.
pub fn name(code: u32) -> &'static str {
    KEY_NAMES
        .get(code as usize)
        .copied()
        .unwrap_or("RC_UNKNOWN")
}

/// Resolve a key name (with or without the `RC_` prefix, ASCII case-insensitive).
pub fn resolve(name: &str) -> Option<u32> {
    let want = name.trim();
    if want.is_empty() {
        return None;
    }
    if let Some(i) = KEY_NAMES.iter().position(|n| n.eq_ignore_ascii_case(want)) {
        return Some(i as u32);
    }
    let upper = want.to_ascii_uppercase();
    let prefixed = if upper.starts_with("RC_") {
        upper
    } else {
        format!("RC_{upper}")
    };
    KEY_NAMES
        .iter()
        .position(|n| *n == prefixed)
        .map(|i| i as u32)
}
